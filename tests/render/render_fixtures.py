"""Builders for minimal draw.io-like SVG fixtures and synthetic devices.

Not a test module (no ``test_`` prefix). The three rendered variants found in
the corpus are reproduced: flat, grouped (per-element ``<g>`` wrappers without
ids) and cell-id (``g[@data-cell-id]``). Rendered coordinates are the model
geometry shifted by ``RENDER_OFFSET`` so offset derivation can be checked.
"""

from __future__ import annotations

import base64
import urllib.parse
import zlib
from dataclasses import dataclass, field
from pathlib import Path

from lxml import etree

from joystick_diagrams.input.axis import Axis, AxisDirection, AxisSlider
from joystick_diagrams.input.button import Button
from joystick_diagrams.input.device import Device_
from joystick_diagrams.input.hat import Hat, HatDirection

SVG_NS = "http://www.w3.org/2000/svg"
XLINK_NS = "http://www.w3.org/1999/xlink"
XHTML_NS = "http://www.w3.org/1999/xhtml"

DEFAULT_PROLOG = (
    '<?xml version="1.0" encoding="UTF-8"?>\n'
    "<!-- Do not edit this file with editors other than draw.io -->\n"
    '<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" '
    '"http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">\n'
)
RENDER_OFFSET = (7.0, 11.0)
REPO_ROOT = Path(__file__).resolve().parents[2]
CORPUS = sorted((REPO_ROOT / "templates").rglob("*.svg")) + [
    REPO_ROOT / "tests" / "data" / "template_test.svg"
]


@dataclass
class CellSpec:
    id: str
    value: str
    x: float = 10
    y: float = 10
    width: float = 80
    height: float = 30
    style: str = "rounded=0;whiteSpace=wrap;html=1;"
    wrapper: str | None = None  # "UserObject" | "object"
    rendered_html: str | None = None  # inner markup for the foreignObject div
    tooltip: str | None = None
    visible: bool = True
    shape: str = "rect"  # "rect" | "none"
    parent: str = "1"  # another cell id makes this a child of that (group) cell
    rendered: bool = True  # False for invisible group containers


@dataclass
class EdgeSpec:
    id: str
    source: str
    target: str
    d: str = "M 50 40 L 150 40"


@dataclass
class DrawioFixture:
    cells: list[CellSpec] = field(default_factory=list)
    edges: list[EdgeSpec] = field(default_factory=list)
    variant: str = "flat"  # "flat" | "grouped" | "cellid"
    compressed: bool = False
    prolog: str = DEFAULT_PROLOG
    width: int = 400
    height: int = 300


# ── Model ──


def _model_xml(fx: DrawioFixture) -> str:
    graph = etree.Element("mxGraphModel", dx="1", dy="1", grid="1")
    root = etree.SubElement(graph, "root")
    etree.SubElement(root, "mxCell", id="0")
    etree.SubElement(root, "mxCell", id="1", parent="0")
    by_id = {cell.id: cell for cell in fx.cells}
    for cell in fx.cells:
        attrs = {"style": cell.style, "vertex": "1", "parent": cell.parent}
        if not cell.visible:
            attrs["visible"] = "0"
        parent = by_id.get(cell.parent)
        origin = (parent.x, parent.y) if parent is not None else (0, 0)
        if cell.wrapper:
            holder = etree.SubElement(root, cell.wrapper, label=cell.value, id=cell.id)
            if cell.tooltip is not None:
                holder.set("tooltip", cell.tooltip)
            mx = etree.SubElement(holder, "mxCell", **attrs)
        else:
            mx = etree.SubElement(root, "mxCell", id=cell.id, value=cell.value, **attrs)
        etree.SubElement(
            mx,
            "mxGeometry",
            x=str(cell.x - origin[0]),
            y=str(cell.y - origin[1]),
            width=str(cell.width),
            height=str(cell.height),
        ).set("as", "geometry")
    for edge in fx.edges:
        mx = etree.SubElement(
            root,
            "mxCell",
            id=edge.id,
            style="edgeStyle=orthogonalEdgeStyle;html=1;",
            edge="1",
            parent="1",
        )
        if edge.source:
            mx.set("source", edge.source)
        if edge.target:
            mx.set("target", edge.target)
        etree.SubElement(mx, "mxGeometry", relative="1").set("as", "geometry")
    return etree.tostring(graph, encoding="unicode")


def compress_diagram(graph_xml: str) -> str:
    compressor = zlib.compressobj(9, zlib.DEFLATED, -15)
    data = compressor.compress(urllib.parse.quote(graph_xml, safe="").encode())
    data += compressor.flush()
    return base64.b64encode(data).decode("ascii")


def _content(fx: DrawioFixture) -> str:
    graph_xml = _model_xml(fx)
    mxfile = etree.Element("mxfile", host="test")
    diagram = etree.SubElement(mxfile, "diagram", id="d1", name="Page-1")
    if fx.compressed:
        diagram.text = compress_diagram(graph_xml)
    else:
        diagram.append(etree.fromstring(graph_xml))
    return etree.tostring(mxfile, encoding="unicode")


# ── Rendered body ──


def _label_group(cell: CellSpec) -> etree._Element:
    x, y = cell.x + RENDER_OFFSET[0], cell.y + RENDER_OFFSET[1]
    g = etree.Element(f"{{{SVG_NS}}}g", transform="translate(-0.5 -0.5)")
    switch = etree.SubElement(g, f"{{{SVG_NS}}}switch")
    fo = etree.SubElement(
        switch, f"{{{SVG_NS}}}foreignObject", width="100%", height="100%"
    )
    outer = etree.SubElement(
        fo,
        f"{{{XHTML_NS}}}div",
        style=f"display: flex; width: {cell.width - 2}px; padding-top: {y + cell.height / 2}px; margin-left: {x + 1}px;",
    )
    middle = etree.SubElement(outer, f"{{{XHTML_NS}}}div", style="font-size: 0px;")
    inner_markup = cell.rendered_html if cell.rendered_html is not None else cell.value
    inner = etree.fromstring(
        f'<div xmlns="{XHTML_NS}" style="display: inline-block; font-size: 12px;">'
        f"{inner_markup}</div>"
    )
    middle.append(inner)
    text = etree.SubElement(
        switch,
        f"{{{SVG_NS}}}text",
        x=str(x + cell.width / 2),
        y=str(y + cell.height / 2 + 4),
        fill="#000000",
    )
    text.text = " ".join(inner.itertext())
    return g


def _shape(cell: CellSpec) -> etree._Element | None:
    if cell.shape == "none":
        return None
    return etree.Element(
        f"{{{SVG_NS}}}rect",
        x=str(cell.x + RENDER_OFFSET[0]),
        y=str(cell.y + RENDER_OFFSET[1]),
        width=str(cell.width),
        height=str(cell.height),
        fill="#ffffff",
        stroke="#000000",
    )


def _edge_path(edge: EdgeSpec) -> etree._Element:
    path = etree.Element(f"{{{SVG_NS}}}path", d=edge.d, fill="none", stroke="#000000")
    path.set("pointer-events", "stroke")  # as draw.io emits edge strokes
    return path


def _append_cell(main: etree._Element, cell: CellSpec, variant: str) -> None:
    shape = _shape(cell)
    label = _label_group(cell)
    if variant == "flat":
        if shape is not None:
            main.append(shape)
        main.append(label)
        return
    if variant == "grouped":
        if shape is not None:
            etree.SubElement(main, f"{{{SVG_NS}}}g").append(shape)
        etree.SubElement(main, f"{{{SVG_NS}}}g").append(label)
        return
    cell_group = etree.SubElement(main, f"{{{SVG_NS}}}g")
    cell_group.set("data-cell-id", cell.id)
    if shape is not None:
        etree.SubElement(cell_group, f"{{{SVG_NS}}}g").append(shape)
    etree.SubElement(cell_group, f"{{{SVG_NS}}}g").append(label)


def _append_edge(main: etree._Element, edge: EdgeSpec, variant: str) -> None:
    path = _edge_path(edge)
    if variant == "cellid":
        cell_group = etree.SubElement(main, f"{{{SVG_NS}}}g")
        cell_group.set("data-cell-id", edge.id)
        etree.SubElement(cell_group, f"{{{SVG_NS}}}g").append(path)
    elif variant == "grouped":
        etree.SubElement(main, f"{{{SVG_NS}}}g").append(path)
    else:
        main.append(path)


def build_svg(fx: DrawioFixture) -> str:
    """A complete template text: prolog + root (content attribute) + body."""
    root = etree.Element(f"{{{SVG_NS}}}svg", nsmap={None: SVG_NS, "xlink": XLINK_NS})
    root.set("version", "1.1")
    root.set("width", f"{fx.width}px")
    root.set("height", f"{fx.height}px")
    root.set("viewBox", f"-0.5 -0.5 {fx.width} {fx.height}")
    root.set("content", _content(fx))
    etree.SubElement(root, f"{{{SVG_NS}}}defs")
    main = etree.SubElement(root, f"{{{SVG_NS}}}g")
    if fx.variant == "cellid":
        layer0 = etree.SubElement(main, f"{{{SVG_NS}}}g")
        layer0.set("data-cell-id", "0")
        main = etree.SubElement(layer0, f"{{{SVG_NS}}}g")
        main.set("data-cell-id", "1")
    for cell in fx.cells:
        if cell.visible and cell.rendered:
            _append_cell(main, cell, fx.variant)
    for edge in fx.edges:
        _append_edge(main, edge, fx.variant)
    banner = etree.SubElement(root, f"{{{SVG_NS}}}switch")
    etree.SubElement(banner, f"{{{SVG_NS}}}g", requiredFeatures="x")
    link = etree.SubElement(banner, f"{{{SVG_NS}}}a")
    etree.SubElement(
        link, f"{{{SVG_NS}}}text"
    ).text = "Text is not SVG - cannot display"
    body = etree.tostring(root, encoding="unicode")
    return f"{fx.prolog}{body}\n"


