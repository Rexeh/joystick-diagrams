def new_device(name: str = "Test Device") -> Device_:
    return Device_("666ec0a0-556b-11ee-8002-444553540000", name)


def _bind_button(dev: Device_, token: str, index: int) -> None:
    # Legacy costs one regex pass over the whole file per token, so the binding
    # is kept sparse: every third button, modifiers on every sixth and tenth.
    number = int(token.split("_")[1])
    if index % 3 == 0:
        dev.create_input(Button(number), f"cmd {token.replace('_', ' ')}")
    if index % 6 == 0:
        dev.add_modifier_to_input(Button(number), {"LShift"}, f"mod {index}")
    if index % 10 == 0:
        dev.add_modifier_to_input(Button(number), {"LCtrl"}, f"mod ctrl {index}")


def _bind_axis(dev: Device_, token: str) -> None:
    parts = token.upper().split("_")
    if parts[1] == "SLIDER" and len(parts) == 3 and parts[2].isdigit():
        dev.create_input(AxisSlider(int(parts[2])), f"cmd slider {parts[2]}")
    elif len(parts) == 2 and parts[1] in AxisDirection.__members__:
        dev.create_input(Axis(AxisDirection[parts[1]]), f"cmd axis {parts[1].lower()}")


def _bind_hat(dev: Device_, token: str, index: int) -> None:
    parts = token.upper().split("_")
    if parts[2] in HatDirection.__members__ and index % 2 == 0:
        dev.create_input(
            Hat(int(parts[1]), HatDirection[parts[2]]), f"cmd hat {parts[1]} {parts[2]}"
        )


def synthetic_device(template, *, special_text: bool = False) -> Device_:
    """Bind a deterministic subset of the tokens a Template discovers.

    Commands never contain tokens (``cmd button 15``), so legacy's chained
    replacement (bug 5) is not triggered. ``special_text`` adds a pre-escaped
    ``&amp;``, quotes and angle brackets to the first button.
    """
    dev = new_device()
    for index, token in enumerate(sorted(template.get_template_buttons())):
        _bind_button(dev, token, index)
    for token in sorted(template.get_template_axis()):
        _bind_axis(dev, token)
    for index, token in enumerate(sorted(template.get_template_hats())):
        _bind_hat(dev, token, index)
    if special_text and template.get_template_buttons():
        first = int(sorted(template.get_template_buttons())[0].split("_")[1])
        dev.create_input(Button(first), 'Fire &amp; "Forget" <now>')
    return dev
